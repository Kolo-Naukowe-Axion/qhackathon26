// Render fixed, trusted TeX at authoring time; the viewer loads no math JavaScript.
import {readFile,writeFile,mkdir,cp} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const base=new URL('./catering-showcase/',import.meta.url);
const assets=new URL('../presentation/assets/math/',import.meta.url);
const source=new URL('quantum-equations.json',base),output=new URL('equations.js',assets);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const manifestPath=new URL('quantum-typesetting.json',base);
if(process.argv.includes('--check')){
 const manifest=JSON.parse(await readFile(manifestPath,'utf8'));
 for(const [name,hash]of Object.entries(manifest.sha256)){
  if(sha(await readFile(new URL(name,assets)))!==hash)throw Error(`Stale equation typesetting: ${name}. Run npm run math:write.`);
 }
 console.log('TeX, generated equations and local fonts match.');
}else{
 await mkdir(assets,{recursive:true});
 const {default:katex}=await import('katex');
 const equations=JSON.parse(await readFile(source,'utf8'));
 const html=Object.fromEntries(Object.entries(equations).map(([key,tex])=>[key,katex.renderToString(tex,{displayMode:true,throwOnError:true,trust:false,output:'htmlAndMathml',strict:'error'})]));
 await writeFile(output,'// Generated by npm run math:write from quantum-equations.json.\nexport default '+JSON.stringify(html,null,2)+';\n');
 await mkdir(new URL('katex/',assets),{recursive:true});
 await cp(new URL('../node_modules/katex/dist/katex.min.css',import.meta.url),new URL('katex/katex.min.css',assets));
 await cp(new URL('../node_modules/katex/dist/fonts/',import.meta.url),new URL('katex/fonts/',assets),{recursive:true});
 await cp(new URL('../node_modules/katex/LICENSE',import.meta.url),new URL('katex/LICENSE',assets));
 const {readdir}=await import('node:fs/promises');
 const paths=['../../../scripts/catering-showcase/quantum-equations.json','equations.js','katex/katex.min.css','katex/LICENSE',...(await readdir(new URL('katex/fonts/',assets))).map(n=>'katex/fonts/'+n)];
 const hashes={};for(const name of paths)hashes[name]=sha(await readFile(new URL(name,assets)));
 await writeFile(manifestPath,JSON.stringify({engine:'KaTeX',version:katex.version,license:'MIT',source:'https://github.com/KaTeX/KaTeX',sha256:hashes},null,2)+'\n');
 console.log('Equation sheet rendered with KaTeX '+katex.version+'.');
}
